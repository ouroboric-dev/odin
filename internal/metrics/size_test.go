// lines is n lines of text, the first one first.
func lines(first string, n int) string {
	var b strings.Builder
	b.WriteString(first + "\n")
	for i := 2; i <= n; i++ {
		fmt.Fprintf(&b, "line %d\n", i)
	}
	return b.String()
}

func gitIn(t *testing.T, dir string, args ...string) string {
	t.Helper()
	out, err := git.Run(context.Background(), dir, args...)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// sizedLeaf is a project with the leaf repos/api, checked out, and one commit on its main that adds 100
// hand-written lines, 50 lines of tests and 30 generated ones, and a binary file. It returns the project, the
// commit before and the commit that adds them.
func sizedLeaf(t *testing.T) (project, base, land string) {
	t.Helper()
	project = treetest.Project(t, "repos/api")
	gitIn(t, project, "submodule", "update", "--init", "--", "repos/api")
	leaf := filepath.Join(project, "repos", "api")
	base = gitIn(t, leaf, "rev-parse", "HEAD")
	files := map[string]string{
		"main.go":               lines("package main", 94),
		"late.go":               lines("package main", 5) + "// DO NOT EDIT is on the sixth line, too late to make this file generated\n",
		"api_test.go":           lines("package main", 20),
		"web/app.test.ts":       lines("test('a')", 10),
		"web/view.test.tsx":     lines("test('b')", 5),
		"web/form.spec.ts":      lines("test('c')", 5),
		"e2e/flow.js":           lines("// a flow", 10),
		"api.pb.go":             "// Code generated by protoc-gen-go.\n" + lines("package main", 9),
		"go.sum":                lines("example.com/a v1.0.0 h1:x=", 10),
		"web/package-lock.json": lines("{", 10),
		"logo.png":              "\x89PNG\r\n\x1a\n\x00\x00\x00binary",
	}
	for name, body := range files {
		p := filepath.Join(leaf, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	gitIn(t, leaf, "add", "-A")
	gitIn(t, leaf, "commit", "-q", "-m", "the task's work")
	return project, base, gitIn(t, leaf, "rev-parse", "HEAD")
}

func TestTheRecordMeasuresEachTasksSize(t *testing.T) {
	project, base, land := sizedLeaf(t)
	t1 := feature("gallery-T1", "repos/api", schema.TaskDone, "")
	t1.Size = "M"
	t2 := feature("gallery-T2", "repos/api", schema.TaskTodo, "")
	f := newFake(t).features(t1, t2)
	f.State.Root = project
	f.State.Loops = map[string]*run.LoopRecord{"gallery-t1-implement": {Base: base}}
	f.log(0, gungnir.Event{Name: gungnir.EventRunStarted})
	f.log(1, gungnir.Event{Name: gungnir.EventLoopAttempt, Node: "gallery-t1-implement", Attempt: 1, Result: "attempt 1 of 3 starts"})
	f.log(2, gungnir.Event{Name: gungnir.EventLoopAttempt, Node: "gallery-t1-implement", Attempt: 2, Result: "attempt 2 of 3 starts"})
	f.log(3, gungnir.Event{Name: gungnir.EventLoopAttempt, Node: "gallery-t1-implement", Attempt: 2, Result: "passed"})
	f.log(4, gungnir.Event{Name: gungnir.EventNodeFinished, Node: "gallery-t1-land", Task: "gallery-t1", Commit: land, Result: "merged into main"})
	// The pointer's commit is the umbrella's, not the leaf's: it is not where the task landed.
	f.log(5, gungnir.Event{Name: gungnir.EventPointerMoved, Node: "gallery-t1-move", Task: "gallery-t1", Commit: strings.Repeat("e", 40)})
	f.log(6, gungnir.Event{Name: gungnir.EventNodeFinished, Node: "gallery-t1-move", Task: "gallery-t1", Commit: strings.Repeat("e", 40), Result: "moved repos/api"})
	r := mustCollect(t, f.done())
	got := r.Tasks[0]
	if got.Size != "M" || got.Attempts != 2 {
		t.Errorf("task 1: size %q, attempts %d; want M and 2", got.Size, got.Attempts)
	}
	if got.Lines == nil || *got.Lines != (Lines{HandWritten: 100, Tests: 50, Generated: 30}) {
		t.Errorf("task 1: lines %+v, want 100 hand-written, 50 tests and 30 generated", got.Lines)
	}
	if other := r.Tasks[1]; other.Lines != nil || other.Attempts != 0 || other.Size != "" {
		t.Errorf("task 2 never ran and has %+v", other)
	}
	if len(r.Warnings) != 0 {
		t.Errorf("warnings = %v", r.Warnings)
	}
}

// A task whose leaf can't be read keeps its other figures; the record says why it has no lines.
func TestATaskWhoseLeafIsGoneHasNoLines(t *testing.T) {
	t1 := feature("gallery-T1", "repos/api", schema.TaskDone, "")
	f := newFake(t).features(t1)
	f.State.Root = t.TempDir()
	f.State.Loops = map[string]*run.LoopRecord{"gallery-t1-implement": {Base: strings.Repeat("a", 40)}}
	f.log(0, gungnir.Event{Name: gungnir.EventRunStarted})
	f.log(1, gungnir.Event{Name: gungnir.EventNodeFinished, Node: "gallery-t1-land", Task: "gallery-t1", Commit: strings.Repeat("b", 40), Result: "merged into main"})
	r := mustCollect(t, f.done())
	if r.Tasks[0].Lines != nil {
		t.Errorf("lines = %+v", r.Tasks[0].Lines)
	}
	if !strings.Contains(strings.Join(r.Warnings, "\n"), "gallery-T1") {
		t.Errorf("warnings = %v, want one that names the task", r.Warnings)
	}
}
